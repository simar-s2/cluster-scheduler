package clusterscheduler.experiments;

import com.fasterxml.jackson.databind.JsonNode;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;

/**
 * Rebuilds the results tables in README.md from results/*.json. Every number
 * in them comes from a file an experiment wrote; nothing is typed in. The
 * tables sit between two marker comments, and only that part of the README
 * is replaced.
 */
public final class ReadmeResults {
    private static final Path README = Path.of("README.md");
    private static final String START_MARKER =
            "<!-- results:begin (generated by `make results` from results/*.json; do not edit by hand) -->";
    private static final String END_MARKER = "<!-- results:end -->";

    private ReadmeResults() {}

    public static void main(String[] args) throws IOException {
        String tables = String.join("\n\n",
                leaderCrashTable(read("failover-chaos")),
                workerCrashTable(read("node-failure")),
                packingTable(read("packing")));
        replaceTables(tables);
        System.out.println("Updated the results tables in " + README);
    }

    private static String leaderCrashTable(JsonNode results) {
        JsonNode failovers = field(results, "failovers");
        JsonNode doubles = field(results, "doublePlacements");
        JsonNode jobs = field(results, "jobs");
        JsonNode fencing = field(results, "fencing");
        return table("Leader crash test",
                row("Times the leader was taken down", count(field(failovers, "total"))
                        + " (" + count(field(failovers, "byKill")) + " killed, "
                        + count(field(failovers, "byPause")) + " frozen)"),
                row("Jobs on two workers at once, from the database's history",
                        bold(count(field(doubles, "jobsWithOverlappingActiveAssignmentsInDatabase")))),
                row("Jobs that ran on two workers at once, from the workers' logs",
                        bold(count(field(doubles, "jobsRunOnTwoNodesAtOnceInWorkerLogs")))),
                row("Jobs ever given to a second worker", count(field(doubles, "jobsAssignedToMoreThanOneNodeInDatabase"))),
                row("Assignments started twice", count(field(doubles, "assignmentsStartedTwiceInWorkerLogs"))),
                row("Jobs submitted during the test, and how many finished",
                        count(field(jobs, "accepted")) + " and " + count(field(jobs, "finished"))),
                row("Healthy workers wrongly declared dead", count(field(results, "nodesDeclaredDead"))),
                row("Time to get a new leader", typicalAndSlowest(field(failovers, "millisUntilNewLeader"))),
                row("Writes from an old leader that the database refused", count(field(fencing, "controlPlaneWritesRejected"))),
                row("Frozen leaders' sessions that PostgreSQL ended",
                        count(field(fencing, "controlPlaneTransactionsEndedByIdleTimeout"))),
                row("Assignments from an old leader that workers refused",
                        count(field(fencing, "workerStaleEpochRejections"))));
    }

    private static String workerCrashTable(JsonNode results) {
        JsonNode recovery = field(results, "millisUntilAllTasksRunningElsewhere");
        return table("Worker crash test",
                row("Workers killed", count(field(recovery, "count")) + ", each running " + jobsOnKilledWorkers(results) + " jobs"),
                row("Time until all its jobs ran on other workers", typicalAndSlowest(recovery)),
                row("Time until it was declared dead", typicalAndSlowest(field(results, "millisUntilDeclaredDead"))),
                row("Jobs on two workers at once, from the database's history",
                        bold(count(field(results, "jobsWithOverlappingActiveAssignmentsInDatabase")))));
    }

    private static String packingTable(JsonNode results) {
        JsonNode config = field(results, "config");
        JsonNode cpu = field(results, "cpuUtilizationWhileJobsWereWaiting");
        JsonNode workerMemory = field(results, "workerContainerMemoryMib");
        return table("Packing test",
                row("Jobs and workers", count(field(config, "jobs")) + " jobs on " + count(field(config, "nodes"))
                        + " workers, in " + count(field(config, "workerContainers")) + " containers"),
                row("CPU utilization while jobs were waiting",
                        bold(percent(field(cpu, "mean"))) + " average, " + percent(field(cpu, "min")) + " lowest"),
                row("CPU the workers themselves reported using",
                        percent(field(field(results, "workerReportedCpuUtilizationWhileJobsWereWaiting"), "mean")) + " average"),
                row("Memory utilization while jobs were waiting",
                        percent(field(field(results, "memoryUtilizationWhileJobsWereWaiting"), "mean")) + " average"),
                row("Time to finish every job", String.format(Locale.ROOT, "%.0f s (%.1f jobs per second)",
                        field(results, "secondsUntilAllJobsFinished").asDouble(),
                        field(results, "jobsFinishedPerSecond").asDouble())),
                row("Time for one round of scheduling decisions",
                        String.format(Locale.ROOT, "%.1f ms average", field(results, "meanSchedulingPassMillis").asDouble())),
                row("Memory per worker container", String.format(Locale.ROOT, "%.0f MiB average, %.0f MiB highest",
                        field(workerMemory, "mean").asDouble(), field(workerMemory, "max").asDouble())),
                row("Healthy workers wrongly declared dead", count(field(results, "nodesDeclaredDead"))));
    }

    /** "8" when every trial killed a worker with the same number of jobs, otherwise a range. */
    private static String jobsOnKilledWorkers(JsonNode results) {
        long fewest = Long.MAX_VALUE;
        long most = 0;
        for (JsonNode trial : field(results, "trials")) {
            long jobs = field(trial, "tasksOnKilledNode").asLong();
            fewest = Math.min(fewest, jobs);
            most = Math.max(most, jobs);
        }
        return fewest == most ? Long.toString(most) : fewest + " to " + most;
    }

    private static JsonNode read(String name) throws IOException {
        return ResultsFile.JSON.readTree(ResultsFile.DIRECTORY.resolve(name + ".json").toFile());
    }

    /** A missing field fails loudly instead of quietly printing 0 in the README. */
    private static JsonNode field(JsonNode node, String name) {
        JsonNode value = node.get(name);
        if (value == null) {
            throw new IllegalStateException("Results file has no field " + name);
        }
        return value;
    }

    private static String table(String title, String... rows) {
        return "**" + title + "**\n\n| | Result |\n|---|---|\n" + String.join("\n", rows);
    }

    private static String row(String measurement, String result) {
        return "| " + measurement + " | " + result + " |";
    }

    private static String bold(String value) {
        return "**" + value + "**";
    }

    private static String count(JsonNode value) {
        return String.format(Locale.ROOT, "%,d", value.asLong());
    }

    private static String typicalAndSlowest(JsonNode millis) {
        return String.format(Locale.ROOT, "%,d ms typical, %,d ms slowest",
                Math.round(field(millis, "median").asDouble()), Math.round(field(millis, "max").asDouble()));
    }

    private static String percent(JsonNode fraction) {
        return String.format(Locale.ROOT, "%.1f%%", 100 * fraction.asDouble());
    }

    private static void replaceTables(String tables) throws IOException {
        String readme = Files.readString(README, StandardCharsets.UTF_8);
        int start = readme.indexOf(START_MARKER);
        int end = readme.indexOf(END_MARKER);
        if (start < 0 || end < start) {
            throw new IllegalStateException("README.md needs " + START_MARKER + " and " + END_MARKER);
        }
        String updated = readme.substring(0, start + START_MARKER.length()) + "\n\n" + tables + "\n\n"
                + readme.substring(end);
        Files.writeString(README, updated, StandardCharsets.UTF_8);
    }
}
